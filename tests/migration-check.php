<?php
/**
 * Plugin::init() must not query the stored schema version on every request
 * (#11421): the settings never go through the object cache, so that check is a
 * direct SELECT. The generated early config records the schema version it was
 * written from; while it records the current one, front-end requests skip the
 * query. Migration semantics stay: a file from before an update makes the
 * first request of any kind migrate, and administrator, cron and WP-CLI
 * requests always ask the database, so settings restored behind the file are
 * still migrated.
 *
 * Plugin::init() runs against stubs; maybe_upgrade() is stopped at its first
 * step after its own database check, which proves the migration started.
 *
 * Run directly with: php tests/migration-check.php
 */

declare(strict_types=1);

// A test script, not part of the plugin: never run it through a web server.
if ( 'cli' !== PHP_SAPI ) {
	exit;
}

$test_content = sys_get_temp_dir() . '/simple-redis-cache-migration-' . bin2hex( random_bytes( 8 ) );
if ( ! mkdir( $test_content, 0700 ) && ! is_dir( $test_content ) ) {
	throw new RuntimeException( 'Could not create the migration test directory.' );
}

define( 'ABSPATH', dirname( __DIR__ ) . '/' );
define( 'WP_CONTENT_DIR', $test_content );
define( 'SIMPLE_REDIS_CACHE_BASENAME', 'simple-redis-cache/simple-redis-cache.php' );

final class SRC_Test_Upgrade_Started extends RuntimeException {
}

/** Counts the direct SELECTs Config::stored() makes. */
final class SRC_Test_WPDB {
	public string $options = 'wp_options';
	public int $selects = 0;
	/** @var array<string, mixed>|null The stored settings, or null for no row. */
	public ?array $settings = null;

	public function prepare( string $query, mixed ...$args ): string {
		return vsprintf( str_replace( '%s', "'%s'", $query ), $args );
	}

	public function get_var( string $query ): ?string {
		unset( $query );
		++$this->selects;
		return null === $this->settings ? null : serialize( $this->settings );
	}
}

$GLOBALS['wpdb']          = new SRC_Test_WPDB();
$GLOBALS['src_test_mode'] = 'front';

function is_multisite(): bool {
	return false;
}

function is_admin(): bool {
	return 'admin' === $GLOBALS['src_test_mode'];
}

function wp_doing_cron(): bool {
	return 'cron' === $GLOBALS['src_test_mode'];
}

function add_action( string $hook, mixed $callback, int $priority = 10, int $accepted_args = 1 ): bool {
	unset( $hook, $callback, $priority, $accepted_args );
	return true;
}

function maybe_unserialize( mixed $value ): mixed {
	return is_string( $value ) ? unserialize( $value ) : $value;
}

function get_option( string $name, mixed $default_value = false ): mixed {
	unset( $name );
	return $default_value;
}

/** maybe_upgrade() loads translations right after its own check: stop there. */
function load_plugin_textdomain( string $domain, mixed $deprecated = false, mixed $path = false ): bool {
	unset( $domain, $deprecated, $path );
	throw new SRC_Test_Upgrade_Started( 'maybe_upgrade() started migrating.' );
}

final class Simple_Redis_Cache_GitHub_Updater {
}

final class Simple_Redis_Cache_Admin {
	public static function init(): void {
	}
}

final class Simple_Redis_Cache_Cleanup {
	public static function init(): void {}
}
final class Simple_Redis_Cache_Abilities {
	public static function init(): void {}
}
final class Simple_Redis_Cache_Page_Invalidator {
	public static function init(): void {
	}
}

require_once dirname( __DIR__ ) . '/includes/class-simple-redis-cache-early-config.php';
require_once dirname( __DIR__ ) . '/includes/class-simple-redis-cache-config.php';
require_once dirname( __DIR__ ) . '/includes/class-simple-redis-cache-plugin.php';

$failures = array();
$assert   = static function ( bool $condition, string $message ) use ( &$failures ): void {
	if ( ! $condition ) {
		$failures[] = $message;
	}
};

$plugin_class = new ReflectionClass( Simple_Redis_Cache_Plugin::class );
$config_file  = Simple_Redis_Cache_Early_Config::path();
$current      = Simple_Redis_Cache_Early_Config::CONFIG_VERSION;

/**
 * One request: the generated file records $file_version (null: no file, false:
 * a file without a version), the database stores $stored_version.
 *
 * @return array{0: int, 1: bool} SELECTs made, and whether migration started.
 */
$run = static function ( string $mode, int|false|null $file_version, int $stored_version ) use ( $plugin_class, $config_file ): array {
	if ( is_file( $config_file ) ) {
		unlink( $config_file );
	}
	if ( null !== $file_version ) {
		$config = Simple_Redis_Cache_Early_Config::defaults();
		if ( false === $file_version ) {
			unset( $config['config_version'] );
		} else {
			$config['config_version'] = $file_version;
		}
		file_put_contents( $config_file, "<?php\n/** Generated by Simple Redis Cache. */\nreturn " . var_export( $config, true ) . ";\n" );
	}
	if ( function_exists( 'opcache_invalidate' ) ) {
		@opcache_invalidate( $config_file, true );
	}
	Simple_Redis_Cache_Early_Config::reset();

	$GLOBALS['src_test_mode']    = $mode;
	$GLOBALS['wpdb']->selects    = 0;
	$GLOBALS['wpdb']->settings   = array( 'config_version' => $stored_version );
	$plugin_class->getProperty( 'initialized' )->setValue( null, false );
	$plugin_class->getProperty( 'upgrade_checked' )->setValue( null, false );

	$started = false;
	try {
		Simple_Redis_Cache_Plugin::init();
	} catch ( SRC_Test_Upgrade_Started $started_upgrade ) {
		$started = true;
	}

	return array( $GLOBALS['wpdb']->selects, $started );
};

try {
	// A current generated config: front-end requests never query.
	[ $selects, $started ] = $run( 'front', $current, $current );
	$assert( 0 === $selects && ! $started, 'A front-end request with a current generated config queried the schema version ' . $selects . ' times.' );
	[ $selects, $started ] = $run( 'front', $current + 1, $current + 1 );
	$assert( 0 === $selects && ! $started, 'A front-end request with a newer generated config queried the schema version.' );

	// Without a trustworthy version in the file, the database decides.
	foreach ( array( 'an older file' => $current - 1, 'no file' => null, 'a file without a version' => false ) as $label => $file_version ) {
		[ $selects, $started ] = $run( 'front', $file_version, $current );
		$assert( 1 === $selects && ! $started, 'A front-end request with ' . $label . ' did not ask the database exactly once: ' . $selects . ' queries.' );
	}

	// Right after an update the file is as old as the stored settings: the first request migrates.
	[ $selects, $started ] = $run( 'front', $current - 1, $current - 1 );
	$assert( $started, 'The first front-end request after an update did not migrate the stored settings.' );

	// Administrator and cron requests always ask, so settings restored behind the file still migrate.
	foreach ( array( 'admin', 'cron' ) as $mode ) {
		[ $selects, $started ] = $run( $mode, $current, $current );
		$assert( 1 === $selects && ! $started, 'A ' . $mode . ' request did not check the stored schema version.' );
		[ $selects, $started ] = $run( $mode, $current, $current - 1 );
		$assert( $started, 'A ' . $mode . ' request did not migrate settings restored behind a current generated config.' );
	}

	// WP-CLI too; defined last, because a constant cannot be undefined.
	define( 'WP_CLI', true );
	[ $selects, $started ] = $run( 'front', $current, $current - 1 );
	$assert( $started, 'A WP-CLI request did not migrate settings restored behind a current generated config.' );
} finally {
	if ( is_file( $config_file ) ) {
		unlink( $config_file );
	}
	rmdir( $test_content );
}

if ( ! empty( $failures ) ) {
	foreach ( $failures as $failure ) {
		fwrite( STDERR, 'FAIL: ' . $failure . "\n" );
	}
	exit( 1 );
}

echo "OK: front-end requests trust a current generated config instead of querying the schema version; updates, administrators, cron and WP-CLI still migrate.\n";
