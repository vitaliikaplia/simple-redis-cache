<?php
/**
 * The early page-cache runtime over real HTTP, through PHP's built-in server, so
 * the response headers it sends can be observed:
 *
 * - the cache-state header needs a valid warming token, not "1";
 * - a warming HIT is never storable by a shared cache;
 * - a page printing a guest nonce caps its s-maxage, and is not served past it;
 * - a network-path request URI (//host/) never reads a page's key.
 *
 * Usage: php tests/page-cache-runtime-http.php
 * Optional environment: SRC_TEST_REDIS_HOST, SRC_TEST_REDIS_PORT.
 */

declare(strict_types=1);

// A test script, not part of the plugin: never run it through a web server.
if ( 'cli' !== PHP_SAPI ) {
	exit;
}

$plugin_dir   = dirname( __DIR__ );
$test_content = sys_get_temp_dir() . '/src-runtime-http-' . bin2hex( random_bytes( 6 ) );
mkdir( $test_content );

define( 'ABSPATH', $plugin_dir . '/' );
define( 'WP_CONTENT_DIR', $test_content );

require_once $plugin_dir . '/includes/class-simple-redis-cache-early-config.php';
require_once $plugin_dir . '/includes/class-simple-redis-cache-redis.php';
require_once $plugin_dir . '/dropins/class-simple-redis-cache-page-request.php';

$failures = array();
$assert   = static function ( bool $condition, string $message ) use ( &$failures ): void {
	if ( ! $condition ) {
		$failures[] = $message;
	}
};

$cleanup = array( 'keys' => array() );
$finish  = static function () use ( &$failures, &$cleanup, $test_content ): void {
	if ( ! empty( $cleanup['process'] ) && is_resource( $cleanup['process'] ) ) {
		proc_terminate( $cleanup['process'] );
		proc_close( $cleanup['process'] );
	}
	if ( ! empty( $cleanup['redis'] ) && ! empty( $cleanup['keys'] ) ) {
		try {
			$cleanup['redis']->del( array_keys( $cleanup['keys'] ) );
		} catch ( Throwable ) {
			// Every key carries the random prefix and a TTL.
		}
	}
	foreach ( (array) glob( $test_content . '/*' ) as $file ) {
		@unlink( (string) $file );
	}
	@rmdir( $test_content );

	if ( ! empty( $failures ) ) {
		fwrite( STDERR, "FAIL:\n- " . implode( "\n- ", $failures ) . "\n" );
		exit( 1 );
	}
};

if ( ! extension_loaded( 'redis' ) || ! function_exists( 'proc_open' ) ) {
	$finish();
	fwrite( STDERR, "SKIP: PhpRedis or proc_open is unavailable.\n" );
	exit( 0 );
}

// A free local port for the built-in server.
$probe = stream_socket_server( 'tcp://127.0.0.1:0', $probe_errno, $probe_error );
$port  = is_resource( $probe ) ? (int) substr( (string) strrchr( (string) stream_socket_get_name( $probe, false ), ':' ), 1 ) : 0;
if ( is_resource( $probe ) ) {
	fclose( $probe );
}

$secret = bin2hex( random_bytes( 32 ) );
$config = Simple_Redis_Cache_Early_Config::defaults();
$config['page']['enabled']                            = true;
$config['page']['ttl']                                = 86400;
$config['page']['shared_max_age']                     = 86400;
$config['page']['invalidate_listings_on_post_update'] = false;
$config['site']['host']                               = '127.0.0.1';
$config['site']['port']                               = $port;
$config['site']['fallback_prefix']                    = 'src-runtime-http-' . bin2hex( random_bytes( 8 ) );
$config['site']['secret']                             = $secret;
$config['redis']['host']                              = getenv( 'SRC_TEST_REDIS_HOST' ) ?: '127.0.0.1';
$config['redis']['port']                              = (int) ( getenv( 'SRC_TEST_REDIS_PORT' ) ?: 6379 );
$config['redis']['timeout']                           = 0.5;
$config['redis']['read_timeout']                      = 0.5;

$redis  = new Simple_Redis_Cache_Redis( $config );
$client = $redis->client();
if ( $port < 1 || null === $client ) {
	$finish();
	fwrite( STDERR, 'SKIP: Redis or a local port is unavailable: ' . (string) $redis->error() . "\n" );
	exit( 0 );
}
$cleanup['redis'] = $client;

// The generated config the runtime reads, and a router that stands in for wp-settings.php.
file_put_contents( Simple_Redis_Cache_Early_Config::path(), "<?php\n/** Generated by Simple Redis Cache. */\nreturn " . var_export( $config, true ) . ";\n" );
$router = $test_content . '/router.php';
file_put_contents(
	$router,
	"<?php\n"
	. 'define( \'ABSPATH\', ' . var_export( $plugin_dir . '/', true ) . " );\n"
	. 'define( \'WP_CONTENT_DIR\', ' . var_export( $test_content, true ) . " );\n"
	. 'require ' . var_export( $plugin_dir . '/dropins/advanced-cache-loader.php', true ) . ";\n"
	. "echo 'FALLTHROUGH';\n"
);

$generation = $redis->generation( 'page' );
$cleanup['keys'][ Simple_Redis_Cache_Early_Config::meta_key( 'page-generation', $config ) ] = true;

/** Store a signed page under the key the runtime will compute for $path. */
$store = static function ( string $path, string $type, array $extra = array(), array $headers = array() ) use ( $config, $client, $generation, $port, $secret, &$cleanup ): string {
	$_COOKIE = array();
	$_SERVER = array(
		'REQUEST_METHOD' => 'GET',
		'HTTP_HOST'      => '127.0.0.1:' . $port,
		'SERVER_PORT'    => (string) $port,
		'REQUEST_URI'    => $path,
	);
	$request   = Simple_Redis_Cache_Page_Request::from_globals( $config );
	$cache_key = null === $request ? '' : $request->cache_key( $generation, $config );
	if ( '' === $cache_key ) {
		return '';
	}

	$serialized = serialize(
		$extra + array(
			'version'   => 4,
			'status'    => 200,
			'type'      => $type,
			'headers'   => array_merge( array( array( 'name' => 'Content-Type', 'value' => 'text/html; charset=UTF-8' ) ), $headers ),
			'body'      => '<!doctype html><html><body>cached page ' . $path . '</body></html>',
			'encoding'  => '',
			'stored_at' => time(),
			'resources' => array(),
		)
	);
	$client->set(
		$cache_key,
		Simple_Redis_Cache_Early_Config::PAGE_PAYLOAD_PREFIX . Simple_Redis_Cache_Early_Config::page_payload_mac( $cache_key, $serialized, $secret ) . $serialized,
		array( 'ex' => 300 )
	);
	$cleanup['keys'][ $cache_key ]           = true;
	$cleanup['keys'][ $cache_key . ':lock' ] = true;

	return $cache_key;
};

$home_key    = $store( '/', 'home' );
$nonce_key   = $store( '/nonce-page/', 'singular', array( 'valid_until' => time() + 500 ) );
$expired_key = $store( '/expired-page/', 'singular', array( 'valid_until' => time() - 5 ) );
$own_key     = $store( '/own-policy/', 'singular', array(), array( array( 'name' => 'Cache-Control', 'value' => 'public, max-age=3600' ) ) );
$assert( '' !== $home_key && '' !== $nonce_key && '' !== $expired_key && '' !== $own_key, 'The test pages could not be keyed.' );

$log     = $test_content . '/server.log';
$process = proc_open(
	array( PHP_BINARY, '-d', 'error_reporting=-1', '-d', 'display_errors=stderr', '-S', '127.0.0.1:' . $port, $router ),
	array(
		0 => array( 'pipe', 'r' ),
		1 => array( 'file', $log, 'a' ),
		2 => array( 'file', $log, 'a' ),
	),
	$pipes,
	$test_content
);
$cleanup['process'] = $process;

$ready = false;
for ( $attempt = 0; $attempt < 50 && ! $ready; $attempt++ ) {
	$socket = @stream_socket_client( 'tcp://127.0.0.1:' . $port, $errno, $error, 0.2 );
	if ( is_resource( $socket ) ) {
		fclose( $socket );
		$ready = true;
	} else {
		usleep( 100000 );
	}
}
if ( ! $ready ) {
	$finish();
	fwrite( STDERR, "SKIP: PHP's built-in server did not start.\n" );
	exit( 0 );
}

/**
 * Send one raw request, so the request target goes out exactly as written.
 *
 * @param array<string, string> $headers
 * @return array{status: int, headers: array<string, string[]>, body: string}
 */
$http = static function ( string $method, string $target, array $headers = array() ) use ( $port ): array {
	$socket = @stream_socket_client( 'tcp://127.0.0.1:' . $port, $errno, $error, 5 );
	if ( ! is_resource( $socket ) ) {
		return array( 'status' => 0, 'headers' => array(), 'body' => '' );
	}
	stream_set_timeout( $socket, 10 );

	$request = "{$method} {$target} HTTP/1.1\r\nHost: 127.0.0.1:{$port}\r\nConnection: close\r\n";
	foreach ( $headers as $name => $value ) {
		$request .= "{$name}: {$value}\r\n";
	}
	fwrite( $socket, $request . "\r\n" );
	$raw = (string) stream_get_contents( $socket );
	fclose( $socket );

	[ $head, $body ] = array_pad( explode( "\r\n\r\n", $raw, 2 ), 2, '' );
	$lines  = explode( "\r\n", $head );
	$status = (int) ( explode( ' ', (string) array_shift( $lines ) )[1] ?? 0 );
	$parsed = array();
	foreach ( $lines as $line ) {
		[ $name, $value ] = array_pad( explode( ':', $line, 2 ), 2, '' );
		$parsed[ strtolower( trim( $name ) ) ][] = trim( $value );
	}

	return array( 'status' => $status, 'headers' => $parsed, 'body' => $body );
};

$token = static fn( int $expires, string $key = '' ): array => array( 'X-Simple-Redis-Cache-Warm' => Simple_Redis_Cache_Early_Config::warm_token( '' === $key ? $secret : $key, $expires ) );
$state = static fn( array $response ): ?string => $response['headers']['x-simple-redis-cache'][0] ?? null;
$cache = static fn( array $response ): array => $response['headers']['cache-control'] ?? array();
$valid = $token( time() + 600 );

// An ordinary visitor: a HIT the edge may keep, with no cache-state header.
$plain = $http( 'GET', '/' );
$assert( 200 === $plain['status'] && str_contains( $plain['body'], 'cached page /' ), 'The stored home page was not served from the early runtime.' );
$assert( null === $state( $plain ), 'An ordinary request received the cache-state header.' );
$assert( array( 'public, max-age=0, s-maxage=86400' ) === $cache( $plain ), 'An ordinary HIT lost its CDN lifetime: ' . json_encode( $cache( $plain ) ) );

// Anyone can send "1"; it is an ordinary request now.
$forged = $http( 'GET', '/', array( 'X-Simple-Redis-Cache-Warm' => '1' ) );
$assert( null === $state( $forged ), 'X-Simple-Redis-Cache-Warm: 1 still reveals HIT, MISS or BYPASS to anyone.' );
$assert( array( 'public, max-age=0, s-maxage=86400' ) === $cache( $forged ), 'A request with an invalid warming header was not treated as ordinary.' );
$assert( null === $state( $http( 'GET', '/', $token( time() - 1 ) ) ), 'An expired warming token revealed the cache state.' );
$assert( null === $state( $http( 'GET', '/', $token( time() + 600, bin2hex( random_bytes( 32 ) ) ) ) ), 'A warming token signed with another secret revealed the cache state.' );

// The warmer sees the state, and that copy is never storable by a shared cache.
$warm = $http( 'GET', '/', $valid );
$assert( 'HIT' === $state( $warm ) && str_contains( $warm['body'], 'cached page /' ), 'A valid warming token no longer receives the HIT state with the page.' );
$assert( array( 'private, no-store' ) === $cache( $warm ), 'A warming HIT carrying the state header may be stored by a shared cache: ' . json_encode( $cache( $warm ) ) );
$warm_head = $http( 'HEAD', '/', $valid );
$assert( 'HIT' === $state( $warm_head ) && '' === $warm_head['body'], 'A warming HEAD no longer receives the HIT state without a body.' );
$own_plain = $http( 'GET', '/own-policy/' );
$own_warm  = $http( 'GET', '/own-policy/', $valid );
$assert( array( 'public, max-age=3600' ) === $cache( $own_plain ), 'A page\'s own Cache-Control was overwritten for ordinary visitors.' );
$assert( 'HIT' === $state( $own_warm ) && array( 'private, no-store' ) === $cache( $own_warm ), 'A warming HIT kept the page\'s own public Cache-Control: ' . json_encode( $cache( $own_warm ) ) );

// A page whose guest nonce expires soon is offered to the edge only until then.
$nonce_page = $http( 'GET', '/nonce-page/' );
preg_match( '/s-maxage=(\d+)/', implode( ',', $cache( $nonce_page ) ), $edge_match );
$edge_ttl = (int) ( $edge_match[1] ?? -1 );
$assert( str_contains( $nonce_page['body'], 'cached page /nonce-page/' ) && $edge_ttl > 480 && $edge_ttl <= 500, "A page whose guest nonce expires in 500 s got s-maxage={$edge_ttl}." );
$expired = $http( 'GET', '/expired-page/', $valid );
$assert( 'MISS' === $state( $expired ) && str_contains( $expired['body'], 'FALLTHROUGH' ), 'A page whose guest nonce may no longer verify was served.' );
$assert( false === $client->get( $expired_key ), 'A page past its valid_until was left in Redis.' );

// "//host/" is not the home page, whatever parse_url() makes of it.
$network = $http( 'GET', '//127.0.0.1:' . $port . '/', $valid );
$assert( 'BYPASS' === $state( $network ) && str_contains( $network['body'], 'FALLTHROUGH' ), 'A network-path request URI was answered from a page key: ' . (string) $state( $network ) );
$network_short = $http( 'GET', '//127.0.0.1/', $valid );
$assert( 'BYPASS' === $state( $network_short ), 'A network-path request URI without a port was answered from a page key: ' . (string) $state( $network_short ) );

$server_log = (string) @file_get_contents( $log );
$assert( 1 !== preg_match( '/(Deprecated|Warning|Notice|Fatal error):/', $server_log ), "The runtime raised PHP diagnostics:\n" . $server_log );

$finish();
echo "OK: the early runtime keeps its cache state from strangers and its warming and nonce pages from shared caches.\n";
