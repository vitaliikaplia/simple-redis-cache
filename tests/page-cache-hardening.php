/**
 * Build a capture as Page_Capture::start() would, without opening a buffer.
 *
 * @param array<string, mixed> $extra Context overrides.
 */
$new_capture = static function ( string $name, array $extra = array(), ?string $lock_owner = null ) use ( $capture, &$config, $redis, $client, $prefix, &$cleanup ): array {
	$cache_key = $prefix . 'page:1:' . hash( 'sha256', $name );
	$lock_key  = $cache_key . ':lock';
	$token     = bin2hex( random_bytes( 16 ) );
	$cleanup['keys'][ $cache_key ] = true;
	$cleanup['keys'][ $lock_key ]  = true;
	$client->set( $lock_key, $lock_owner ?? $token, array( 'ex' => 30 ) );

	$instance = $capture->newInstanceWithoutConstructor();
	$capture->getProperty( 'context' )->setValue(
		$instance,
		$extra + array(
			'config'     => $config,
			'redis'      => $redis,
			'cache_key'  => $cache_key,
			'lock_key'   => $lock_key,
			'lock_token' => $token,
		)
	);
	$capture->getProperty( 'page_config' )->setValue( $instance, $config['page'] + array( 'ttl' => 86400 ) );
	$capture->getProperty( 'debug_header' )->setValue( $instance, false );

	return array( $instance, $cache_key, $lock_key, $token );
};

