$vary_case = static function ( string $name, array $values ) use ( $new_capture, $prepare_vary, $store, $client, $html ): bool {
	[ $instance, $instance_key ] = $new_capture( $name, array( 'vary_values' => $values ) );
	$prepare_vary->invoke( $instance );
	$store->invoke( $instance, $html );
	return is_string( $client->get( $instance_key ) );
};
