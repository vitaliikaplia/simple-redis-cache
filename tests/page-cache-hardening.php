$key = static function ( ?Simple_Redis_Cache_Page_Request $request ) use ( &$config ): string {
	return null === $request ? '' : $request->cache_key( 1, $config );
};

$assert( null !== $request( '/?s=term' ), 'A lower-case search parameter no longer reaches the search cache.' );
$assert( null === $request( '/?S=term' ), 'An upper-case ?S= was treated as a search, letting any value mint a cached home page.' );

$plain  = $request( '/news/' );
$tagged = $request( '/news/?utm_source=x&gclid=y' );
$assert( null !== $tagged && $key( $plain ) === $key( $tagged ), 'An ignored parameter no longer maps to the canonical key.' );
$assert( null !== $plain && $plain->is_storable(), 'A plain URL is no longer storable.' );
$assert( null !== $tagged && ! $tagged->is_storable(), 'A request with ignored parameters may store its own rendering, which echoes them into links.' );

$upper = $request( '/News/Post/' );
$assert( null !== $upper && ! $upper->is_storable(), 'A path with upper-case letters may be stored, so every case variant becomes its own entry.' );
$assert( ! ( $request( '/%D0%9D%D0%BE%D0%B2%D0%B8%D0%BD%D0%B8/' )?->is_storable() ?? true ), 'An upper-case Cyrillic path may be stored.' );

$cyrillic = $key( $request( '/%d0%bf/' ) );
$assert( '' !== $cyrillic && $cyrillic === $key( $request( '/%D0%BF/' ) ), 'Percent-encoding hex case still splits one page into several keys.' );
$assert( $cyrillic === $key( $request( "/\xD0\xBF/" ) ), 'A raw UTF-8 path and its percent-encoded form use different keys.' );
// WordPress matches the raw path first: /n%65ws-post/ looks up slug "n%65ws-post"
// and renders a 404, so it must never share /news-post/'s key nor be stored.
$assert( $key( $request( '/news-post/' ) ) !== $key( $request( '/n%65ws-post/' ) ), 'An encoded unreserved character shares the live page\'s key, so its 404 could replace the post.' );
$assert( ! ( $request( '/n%65ws-post/' )?->is_storable() ?? true ), 'A path with an encoded unreserved character may be stored.' );
$assert( ! ( $request( '/news%2Dpost/' )?->is_storable() ?? true ), 'A path with an encoded hyphen may be stored.' );
$assert( $key( $request( '/a%2Fb/' ) ) !== $key( $request( '/a/b/' ) ), 'An encoded slash was decoded into a path separator.' );
$assert( null !== $request( '/%d0%bf/' ) && $request( '/%d0%bf/' )->is_storable(), 'A lower-case Cyrillic slug is no longer storable.' );

$english = $request( '/news/', array( 'pll_language' => 'en' ) );
$assert( null !== $english && array( 'pll_language' => 'en' ) === $english->vary_cookie_values(), 'A language vary cookie no longer selects a variant.' );
$assert( null === $request( '/news/', array( 'pll_language' => str_repeat( 'a', 33 ) ) ), 'An over-long vary-cookie value was accepted as a variant.' );
$assert( null === $request( '/news/', array( 'pll_language' => 'en"; x' ) ), 'A vary-cookie value outside the language-code alphabet was accepted.' );
$assert( null !== $plain && array() === $plain->vary_cookie_values(), 'A request without vary cookies reports a variant.' );

